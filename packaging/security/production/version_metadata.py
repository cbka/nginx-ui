#!/usr/bin/env python3
"""Prepare release metadata, then verify the built frontend before Go compilation."""
import argparse
import json
from pathlib import Path
import re
import subprocess

VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?")


def prepare(root, version):
    if not VERSION.fullmatch(version):
        raise ValueError("Expected release version without a v prefix or commit suffix")
    package = root / "app/package.json"
    data = json.loads(package.read_text())
    data["version"] = version
    package.write_text(json.dumps(data, indent=2) + "\n")


def verified_metadata(root):
    package = json.loads((root / "app/package.json").read_text())
    source = json.loads((root / "app/src/version.json").read_text())
    built = json.loads((root / "app/dist/version.json").read_text())
    if source != built or built.get("version") != package["version"]:
        raise ValueError("Frontend metadata mismatch: rebuild frontend before compiling Go")
    for key in ("build_id", "total_build"):
        if type(built.get(key)) is not int or built[key] < 1:
            raise ValueError(f"Invalid built {key}")
    if not VERSION.fullmatch(built["version"]):
        raise ValueError("Invalid built version")
    return built


def generate(root):
    data = verified_metadata(root)
    commit = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if not re.fullmatch(r"[0-9a-f]{40,64}", commit):
        raise ValueError("Invalid commit hash")
    target = root / "internal/version/version.gen.go"
    target.write_text('// Code generated by packaging/security/production/version_metadata.py; DO NOT EDIT.\n\n'
                      'package version\n\nfunc init() {\n'
                      f'\tVersion = {json.dumps(data["version"])}\n'
                      f'\tBuildId = {data["build_id"]}\n'
                      f'\tTotalBuild = {data["total_build"]}\n'
                      f'\tHash = {json.dumps(commit)}\n' + '}\n')
    print(f'Verified frontend/backend metadata: {data["version"]}, build {data["build_id"]}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "generate"))
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument("--version")
    args = parser.parse_args()
    if args.action == "prepare":
        if not args.version:
            parser.error("prepare requires --version")
        prepare(args.root, args.version)
    else:
        generate(args.root)


if __name__ == "__main__":
    main()
