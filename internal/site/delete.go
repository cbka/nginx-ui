package site

import (
	"context"
	"github.com/0xJacky/Nginx-UI/internal/nginx"
	"github.com/0xJacky/Nginx-UI/internal/nodeauth"
	"github.com/0xJacky/Nginx-UI/model"
	"github.com/0xJacky/Nginx-UI/query"
	"os"
)

// syncDelete dispatches the delete request to the site's sync nodes. It is a
// variable so tests can observe whether a delete reached the remote nodes.
var syncDelete = dispatchSyncDelete

// Delete deletes a site by removing the file in sites-available. Every refusal
// check runs before any side effect, so a refused delete leaves the database
// record, the certificate record, the file and the remote nodes untouched. A
// site generated by an ingress is refused unless the Force option is given.
func Delete(ctx context.Context, name string, opts ...MutateOption) (err error) {
	availablePath, err := ResolveAvailablePath(name)
	if err != nil {
		return err
	}

	enabledPath, err := ResolveEnabledPath(name)
	if err != nil {
		return err
	}

	maintenancePath, err := ResolveEnabledMaintenancePath(name)
	if err != nil {
		return err
	}

	availableExists, err := nginx.Exists(availablePath)
	if err != nil {
		return err
	}
	if !availableExists && !nodeauth.IsReplicated(ctx) {
		return ErrSiteNotFound
	}

	if err = CheckManaged(name, opts...); err != nil {
		return err
	}

	enabledExists, err := nginx.Exists(enabledPath)
	if err != nil {
		return err
	}
	if enabledExists {
		return ErrSiteIsEnabled
	}

	maintenanceExists, err := nginx.Exists(maintenancePath)
	if err != nil {
		return err
	}
	if maintenanceExists {
		return ErrSiteIsInMaintenance
	}

	s := query.Site

	// Remote namespaces keep the enablement flag in the database, so refuse the
	// deletion the same way an enabled local site is refused.
	if IsRemoteDeploy(name) {
		siteModel, err := s.Where(s.Path.Eq(availablePath)).First()
		if err == nil && siteModel.RemoteEnabled {
			return ErrSiteIsEnabled
		}
	}

	// The sync nodes are resolved from the site record, so dispatch before the
	// record is deleted.
	if err = syncDelete(ctx, name); err != nil {
		return err
	}

	// Full synchronization of a generated maintenance configuration may have
	// registered its filename as a site. Remove only the exact orphan metadata:
	// never a real config, an enabled site, or an ingress-owned record.
	orphanPath, cleanupErr := orphanMaintenanceMetadataPath(name)
	if cleanupErr != nil {
		return cleanupErr
	}
	deleteQuery := model.UseDB().Where("path = ?", availablePath)
	if orphanPath != "" {
		deleteQuery = deleteQuery.Or("path = ? AND (managed_by = ? OR managed_by IS NULL) AND (remote_enabled = ? OR remote_enabled IS NULL)", orphanPath, "", false)
	}
	err = deleteQuery.Unscoped().Delete(&model.Site{}).Error
	if err != nil {
		return
	}

	certModel := model.Cert{Filename: name}
	_ = certModel.Remove()

	if availableExists {
		return nginx.Remove(availablePath)
	}
	return nil
}

func dispatchSyncDelete(ctx context.Context, name string) error {
	return syncFinalState(ctx, name, "delete")
}

// orphanMaintenanceMetadataPath identifies metadata left by synchronization,
// not an existing independently configured site with a similar name.
func orphanMaintenanceMetadataPath(name string) (string, error) {
	generated := name + MaintenanceSuffix
	available, err := ResolveAvailablePath(generated)
	if err != nil {
		return "", nil
	} // Never clean a suffix path that cannot be resolved safely.
	enabled, err := resolveEnabledSymlinkPath(generated)
	if err != nil {
		return "", err
	}
	maintenance, err := ResolveEnabledMaintenancePath(generated)
	if err != nil {
		return "", nil
	}
	for _, path := range []string{available, enabled, maintenance} {
		_, statErr := nginx.Lstat(path)
		if statErr == nil {
			return "", nil
		}
		if !os.IsNotExist(statErr) {
			return "", statErr
		}
	}
	return available, nil
}
